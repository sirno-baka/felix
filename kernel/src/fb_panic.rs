//! Minimal framebuffer panic / exception console.
//! Active only when bootloader left a valid FramebufferInfo at phys 0x5000.

use core::fmt::{self, Write};
use core::ptr;

use crate::memory::paging::phys_to_virt;

const FB_INFO_PHYS: u32 = 0x0000_5000;

/// Virtual window where we map the LFB for panic drawing (4 MiB large pages).
const FB_VIRT_BASE: u32 = 0xE000_0000;

#[repr(C, packed)]
#[derive(Clone, Copy)]
struct FramebufferInfo {
    address: u32,
    pitch: u16,
    width: u16,
    height: u16,
    bpp: u8,
    reserved: [u8; 3],
}

