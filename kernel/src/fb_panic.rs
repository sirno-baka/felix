struct Fb {
    base: *mut u8,
    pitch: u32,
    width: u32,
    height: u32,
    bpp: u8,
    cx: u32,
    cy: u32,
    cols: u32,
    rows: u32,
}

/// Open FB, clear, dump recent `print!` lines, then write `args`.
pub fn try_show(args: fmt::Arguments) -> bool {
    let mut fb = match open_fb() {
        Some(f) => f,
        None => return false,
    };
    fb.clear();
    dump_recent_log(&mut fb);
    let _ = fb.write_fmt(args);
    true
}

fn dump_recent_log(fb: &mut Fb) {
    // klog is independent of PRINTER's Mutex — always available on panic.
    let _ = write!(fb, "--- recent log ---\n");
    crate::print::klog_for_each_line(|line| {
        for &b in line {
            fb.putc(b as char);
        }
        fb.putc('\n');
    });
    let _ = write!(fb, "------------------\n");
}

/// Kernel panic path.
pub fn try_panic_fb(info: &core::panic::PanicInfo) -> bool {
    if let Some(loc) = info.location() {
        try_show(format_args!(
            "=== KERNEL PANIC ===\nPanic message: {}\nLocation: {}:{}:{}\nSystem halted\n",
            info,
            loc.file(),
            loc.line(),
            loc.column()
        ))
    } else {
        try_show(format_args!(
            "=== KERNEL PANIC ===\nPanic message: {}\nSystem halted\n",
            info
        ))
    }
}

/// CPU exception (kernel mode) — used by interrupts/exceptions.rs.
pub fn try_exception_fb(name: &str, eip: u32, cs: u32, eflags: u32) -> bool {
    try_show(format_args!(
        "=== KERNEL EXCEPTION: {} ===\n  EIP={:#x} CS={:#x} EFLAGS={:#b}\nSystem halted\n",
        name, eip, cs, eflags
    ))
}

/// Page fault with CR2.
pub fn try_page_fault_fb(eip: u32, cs: u32, eflags: u32, cr2: u32) -> bool {
    try_show(format_args!(
        "=== KERNEL EXCEPTION: page_fault ===\n  CR2={:#x}\n  EIP={:#x} CS={:#x} EFLAGS={:#b}\nSystem halted\n",
        cr2, eip, cs, eflags
    ))
}

fn open_fb() -> Option<Fb> {
    let fb_info = read_fb_info();
    if fb_info.address == 0 || fb_info.width == 0 || fb_info.pitch == 0 {
        return None;
    }
    let fb_bytes = fb_info.pitch as u32 * fb_info.height as u32;
    let base = unsafe { map_lfb(fb_info.address, fb_bytes)? };
    Some(Fb {
        base,
        pitch: fb_info.pitch as u32,
        width: fb_info.width as u32,
        height: fb_info.height as u32,
        bpp: fb_info.bpp,
        cx: 0,
        cy: 0,
        cols: (fb_info.width as u32) / 8,
        rows: (fb_info.height as u32) / 8,
    })
}

fn read_fb_info() -> FramebufferInfo {
    let ptr = phys_to_virt(FB_INFO_PHYS) as *const FramebufferInfo;
    unsafe { ptr::read_volatile(ptr) }
}

/// Map LFB at FB_VIRT_BASE with 4 MiB large pages. Returns virtual pointer.
unsafe fn map_lfb(phys: u32, size: u32) -> Option<*mut u8> {
    let mut cr3: u32;
    core::arch::asm!("mov {}, cr3", out(reg) cr3);

    let pd: *mut u32 = if cr3 < 0x0800_0000 {
        phys_to_virt(cr3) as *mut u32
    } else {
        0xFFFF_F000u32 as *mut u32
    };

    let aligned_phys = phys & !0x003F_FFFF;
    let offset = phys - aligned_phys;
    let need = size.saturating_add(offset);
    let pages = ((need + 0x003F_FFFF) / 0x0040_0000) as usize;
    let start_pde = (FB_VIRT_BASE >> 22) as usize;

    if start_pde + pages >= 1023 {
        return None;
    }

    for i in 0..pages {
        let p = aligned_phys + (i as u32) * 0x0040_0000;
        *pd.add(start_pde + i) = p | 0x83;
    }

    core::arch::asm!("mov cr3, {}", in(reg) cr3);

    Some((FB_VIRT_BASE + offset) as *mut u8)
}

impl Fb {
    fn clear(&mut self) {
        let bytes = self.pitch as usize * self.height as usize;
        unsafe {
            ptr::write_bytes(self.base, 0, bytes);
        }
    }

    fn put_pixel(&self, x: u32, y: u32, r: u8, g: u8, b: u8) {
        if x >= self.width || y >= self.height {
            return;
        }
        let bpp = self.bpp;
        let off = (y * self.pitch + x * ((bpp as u32 + 7) / 8)) as usize;
        unsafe {
            let p = self.base.add(off);
            match bpp {
                32 | 24 => {
                    *p = b;
                    *p.add(1) = g;
                    *p.add(2) = r;
                    if bpp == 32 {
                        *p.add(3) = 0;
                    }
                }
                16 => {
                    let v: u16 = ((r as u16 & 0xF8) << 8)
                        | ((g as u16 & 0xFC) << 3)
                        | ((b as u16) >> 3);
                    ptr::write_unaligned(p as *mut u16, v);
                }
                _ => {}
            }
        }
    }

    fn draw_char(&self, col: u32, row: u32, c: char) {
        let ci = c as u32;
        let glyph = if (0x20..0x7F).contains(&ci) {
            &FONT8[(ci - 0x20) as usize]
        } else {
            &FONT8[0]
        };
        let x0 = col * 8;
        let y0 = row * 8;
        for gy in 0..8u32 {
            let bits = glyph[gy as usize];
            for gx in 0..8u32 {
                // LSB = leftmost pixel
                if bits & (1 << gx) != 0 {
                    self.put_pixel(x0 + gx, y0 + gy, 0xC8, 0xC8, 0xC8);
                }
            }
        }
    }

    fn newline(&mut self) {
        self.cx = 0;
        self.cy += 1;
        if self.cy >= self.rows {
            self.cy = self.rows.saturating_sub(1);
        }
    }

    fn putc(&mut self, c: char) {
        if c == '\n' {
            self.newline();
            return;
        }
        if c == '\r' {
            self.cx = 0;
            return;
        }
        if self.cx >= self.cols {
            self.newline();
        }
        self.draw_char(self.cx, self.cy, c);
        self.cx += 1;
    }
}

impl Write for Fb {
    fn write_str(&mut self, s: &str) -> fmt::Result {
        for c in s.chars() {
            self.putc(c);
        }
        Ok(())
    }
}
